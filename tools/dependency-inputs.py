#!/usr/bin/env python3
"""Generate audit inputs from package metadata; no resolver or network access."""
import argparse
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def render(root=ROOT, *, semantic=False):
    data = tomllib.loads((root / "portable/pyproject.toml").read_text())
    project = data["project"]
    requirements = list(project["dependencies"]) + list(data["build-system"]["requires"])
    for extra in ("gui", "build"):
        requirements.extend(project["optional-dependencies"].get(extra, []))
    if semantic:
        requirements.extend(project["optional-dependencies"].get("semantic", []))
    return ("# Generated by tools/dependency-inputs.py; do not edit manually.\n"
            "# Core, GUI and build inputs; optional semantic models are not bundled.\n"
            + "\n".join(sorted(set(requirements), key=str.casefold)) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--semantic", action="store_true")
    args = parser.parse_args()
    value = render(semantic=args.semantic)
    if args.semantic:
        print(value, end="")
    elif args.check:
        if (ROOT / "portable/security-audit-requirements.txt").read_text() != value:
            raise SystemExit("Dependency audit inputs drifted; run tools/dependency-inputs.py")
    else:
        (ROOT / "portable/security-audit-requirements.txt").write_text(value)


if __name__ == "__main__":
    main()
