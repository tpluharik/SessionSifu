import {sanitizeCommand} from '../extension/sessionsifu@local/commandPrivacy.js';
import {CallerGate} from '../extension/sessionsifu@local/callerGate.js';
import {managedExtensionDisposition} from '../extension/sessionsifu@local/installOwnership.js';
import GLib from 'gi://GLib';

function assert(value, message) { if (!value) throw new Error(message); }
const ordinary = ['libreoffice', '--writer', '/home/user/Quarterly report.odt'];
assert(JSON.stringify(sanitizeCommand(ordinary).argv) === JSON.stringify(ordinary), 'Ordinary document argv must stay byte-identical');
assert(!sanitizeCommand(ordinary).requiresInput, 'No false manual hold');
const secret = sanitizeCommand(['app', '--token=private', '--password', 'secret', 'https://user:pass@host/a?token=abc&document=1']);
assert(secret.requiresInput, 'Sensitive commands require input');
assert(!JSON.stringify(secret.argv).includes('private') && !JSON.stringify(secret.argv).includes('secret'), 'No credential persisted');
assert(secret.argv.at(-1).includes('document=1'), 'Preserve non-secret URL fields');
assert(sanitizeCommand(['mysql', '-pvalue']).requiresInput, 'MySQL short password');
assert(!sanitizeCommand(['editor', '-project']).requiresInput, 'Do not interpret unrelated short options as passwords');
assert(sanitizeCommand(null).argv === null, 'Legacy empty command');
assert(sanitizeCommand(['browser', 'https://secret@host/']).requiresInput, 'Token-only URL userinfo');
assert(sanitizeCommand(['app', 'x'.repeat(70000)]).requiresInput, 'Bound oversized metadata');
assert(!sanitizeCommand(['app', 'x-'.repeat(16000)]).requiresInput, 'Long benign text is linear and unchanged');
let owner = ':1.10'; let now = 10000;
const gate = new CallerGate(async () => owner, () => now);
assert(!await gate.allow(':1.20', 'capture'), 'Reject unrelated connection');
assert(await gate.allow(':1.10', 'capture'), 'Allow current manager');
assert(!await gate.allow(':1.10', 'capture'), 'Rate limit');
now += 1001; owner = ':1.11';
assert(!await gate.allow(':1.10', 'capture'), 'Reject former owner after name replacement');
assert(await gate.allow(':1.11', 'capture'), 'Accept new owner without a stale identity cache');
gate.close(); now += 1001;
assert(!await gate.allow(':1.11', 'capture'), 'No callbacks after teardown');
const bounded = new CallerGate(() => new Promise(() => {}));
for (let i = 0; i < 4; i++) bounded.allow(`:1.${i}`, 'capture');
assert(!await bounded.allow(':1.99', 'capture'), 'Bound authorization concurrency');
print('Command privacy and asynchronous D-Bus caller regressions passed');
assert(managedExtensionDisposition({mode: 'standalone'}, false) === 'allow', 'Standalone never requires APT');
assert(managedExtensionDisposition({}, false) === 'allow', 'Unknown legacy ownership preserved');
assert(managedExtensionDisposition({mode: 'apt-backed'}, false) === 'system-removed', 'APT-backed capture stops after removal');
assert(managedExtensionDisposition({mode: 'apt-backed'}, true, '3.5.36', '3.5.35') === 'system-newer', 'Newer APT integration takes priority');
assert(managedExtensionDisposition({mode: 'apt-backed'}, true, '3.5.34', '3.5.35') === 'allow', 'Newer user integration works');
for (let i = 0; i < 1000; i++) sanitizeCommand(ordinary);
const start = GLib.get_monotonic_time();
for (let i = 0; i < 10000; i++) sanitizeCommand(ordinary);
print(`Command-filter microbenchmark: ${((GLib.get_monotonic_time() - start) / 1000).toFixed(3)} ms / 10000 ordinary argv; synthetic only`);
